"""Community and node descriptions, written into graph.json.

Adds a top-level ``communities`` list (one entry per community: ``id``, ``name`` (Graphify's own name,
never changed here), ``description``, ``size``, ``members``) and a ``description`` field on every node.

Modes (GRAPHIFY_DESCRIPTIONS): unset = deterministic template text from structure (no LLM); ``llm`` =
generated by the configured LLM backend (see descriptions_llm.py). Dry run for llm: GRAPHIFY_DESCRIPTIONS_DRY_RUN=1.

CLI:  python -m graphify.descriptions apply <graph.json>
"""
from __future__ import annotations

import json
import os
import sys


def mode() -> str:
    raw = os.environ.get("GRAPHIFY_DESCRIPTIONS", "").strip().lower()
    return "llm" if raw == "llm" else "off"


def apply(graph_json: str, side: dict | None) -> dict:
    """Write the communities list and description fields into ``graph_json`` in place.

    ``side`` is ``{"communities": {cid: {"description": str}}, "nodes": {node_id: str}}`` or None.
    """
    side = side or {}
    with open(graph_json) as fh:
        g = json.load(fh)
    nodes = g["nodes"]
    report = {"communities_described": 0, "nodes_described": 0}

    members: dict = {}
    for n in nodes:
        members.setdefault(str(n.get("community")), []).append(n["id"])

    comm_text = {str(c): (e or {}).get("description") for c, e in (side.get("communities") or {}).items()}
    node_text = side.get("nodes") or {}
    why_text = side.get("why") or {}
    for n in nodes:
        text = node_text.get(n["id"])
        n["description"] = text
        if why_text.get(n["id"]):
            n["why"] = why_text[n["id"]]  # the WHY of a code symbol, from the same call as its description
        if text is not None:
            report["nodes_described"] += 1
        n.pop("community_meaning", None)
        n.pop("community_description", None)

    hub_name: dict = {}
    for n in nodes:
        hub_name.setdefault(str(n.get("community")), n.get("community_name"))
    communities = []
    for cid in sorted((c for c in members if c != "None"), key=lambda c: (0, int(c)) if c.isdigit() else (1, c)):
        desc = comm_text.get(cid)
        if desc is not None:
            report["communities_described"] += 1
        communities.append({
            "id": int(cid) if cid.isdigit() else cid,
            "name": hub_name.get(cid),
            "description": desc,
            "size": len(members[cid]),
            "members": sorted(members[cid]),
        })
    g["communities"] = communities
    g.get("graph", {}).pop("community_info", None)
    with open(graph_json, "w") as fh:
        json.dump(g, fh, indent=2)
    return report


def deterministic_side(g: dict) -> dict:
    """No-LLM descriptions built from structure: kind, folder, triage, tags, and size.

    Same role as the RAG service's structural names and package summaries: a template string per
    node and per community, always filled, never an LLM call.
    """
    import collections
    import os

    nodes = g["nodes"]
    node_text = {}
    for n in nodes:
        kind = str(n.get("kind") or "node").replace("_", " ")
        label = n.get("label") or n.get("id")
        src = n.get("source_file")
        bits = []
        if src:
            bits.append(f"{label} is a {kind} in {src}.")
        else:
            bits.append(f"{label} is an external {kind} reference.")
        if n.get("triage") == "TRIVIAL":
            bits.append("Boilerplate or metadata, not substantive code.")
        if n.get("is_test"):
            bits.append("Test code.")
        tags = n.get("tags") or []
        if tags:
            bits.append("Tags: " + ", ".join(tags[:5]) + ".")
        node_text[n["id"]] = " ".join(bits)

    members = collections.defaultdict(list)
    for n in nodes:
        members[str(n.get("community"))].append(n)
    comm_text = {}
    for cid, ms in members.items():
        if cid == "None":
            continue
        kinds = collections.Counter(str(m.get("kind") or "node").replace("_", " ") for m in ms)
        folders = collections.Counter(os.path.dirname(m.get("source_file") or "") for m in ms if m.get("source_file"))
        tags = collections.Counter(t for m in ms for t in (m.get("tags") or []))
        triage = collections.Counter(m.get("triage") for m in ms)
        kind_str = ", ".join(f"{c} {k}" for k, c in kinds.most_common(3))
        parts = [f"{len(ms)} nodes: {kind_str}."]
        if folders:
            top = folders.most_common(1)[0][0]
            parts.append(f"Mostly under {top}." if top else "Mostly at the repo root.")
        if tags:
            parts.append("Main tags: " + ", ".join(t for t, _ in tags.most_common(5)) + ".")
        parts.append(f"{triage.get('SUBSTANTIAL', 0)} substantive, {triage.get('TRIVIAL', 0)} trivial.")
        comm_text[cid] = " ".join(parts)

    return {
        "communities": {c: {"description": t} for c, t in comm_text.items()},
        "nodes": node_text,
    }


def apply_if_enabled(graph_json: str) -> dict:
    """Always writes the schema. LLM mode uses the backend; otherwise deterministic text."""
    if mode() == "llm":
        from . import descriptions_llm
        side, report = descriptions_llm.generate(graph_json)
        if side is None:
            return {"enabled": True, "mode": "llm", **report}
        # nodes the model did not describe (TRIVIAL ones are skipped) get the template text
        with open(graph_json) as fh:
            g = json.load(fh)
        template = deterministic_side(g)["nodes"]
        side_nodes = dict(side.get("nodes") or {})
        filled = 0
        for nid, text in template.items():
            if not side_nodes.get(nid):
                side_nodes[nid] = text
                filled += 1
        comm_side = dict(side.get("communities") or {})
        comm_filled = 0
        for cid, entry in deterministic_side(g)["communities"].items():
            if not (comm_side.get(cid) or {}).get("description"):
                comm_side[cid] = entry
                comm_filled += 1
        side = {**side, "nodes": side_nodes, "communities": comm_side}
        return apply(graph_json, side) | {"enabled": True, "mode": "llm", "template_filled": filled,
                                          "community_template_filled": comm_filled, **report}
    with open(graph_json) as fh:
        g = json.load(fh)
    return apply(graph_json, deterministic_side(g)) | {"enabled": True, "mode": "deterministic"}


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "apply":
        print(json.dumps(apply_if_enabled(sys.argv[2]), indent=1))
    else:
        print("usage: python -m graphify.descriptions apply <graph.json>")
        sys.exit(2)
